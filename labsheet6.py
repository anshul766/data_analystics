# Q1. What is Predictive Analytics, and how is it used in
# real-world applications?
#
# Answer:
# Predictive Analytics uses historical data, statistical methods
# and machine learning algorithms to predict future outcomes.
# It is used in sales forecasting, house price prediction,
# demand forecasting, risk analysis and customer behavior prediction.


# Q2. Explain the working principle of the Linear Regression
# algorithm.
#
# Answer:
# Linear Regression establishes a mathematical relationship between
# independent variables and a continuous dependent variable.
# It finds the best-fitting line by minimizing the difference between
# actual and predicted values.
#
# General equation:
#
# Y = b0 + b1X1 + b2X2 + ... + bnXn
#
# Where:
# Y = Predicted value
# b0 = Intercept
# b1, b2, ... = Regression coefficients
# X1, X2, ... = Independent variables


# Q3. Differentiate between dependent and independent variables
# with suitable examples.
#
# Answer:
# Independent variables are input variables used for prediction.
# The dependent variable is the output that we want to predict.
#
# Example:
# Independent variables = income, house age, rooms, population
# Dependent variable = house price


# Q4. Why is it necessary to split the dataset into training
# and testing sets?
#
# Answer:
# The training dataset is used to train the model.
# The testing dataset is used to evaluate the model on unseen data.
# It helps determine whether the model can generalize to new data.


# Q5. What is the significance of the R² Score in regression
# analysis?
#
# Answer:
# R² Score measures how much variation in the dependent variable
# is explained by the regression model.
#
# A value closer to 1 generally means that the model explains more
# variation in the target variable.


# Q6. Differentiate between MAE, MSE, and RMSE. Which metric is
# more sensitive to large prediction errors?
#
# Answer:
#
# MAE (Mean Absolute Error):
# It calculates the average absolute difference between actual
# and predicted values.
#
# MSE (Mean Squared Error):
# It calculates the average squared difference between actual
# and predicted values.
#
# RMSE (Root Mean Squared Error):
# It is the square root of MSE and is expressed in the same units
# as the target variable.
#
# MSE and RMSE are more sensitive to large prediction errors
# because the errors are squared.


# Q7. What assumptions should be satisfied before applying
# Linear Regression?
#
# Answer:
# Important assumptions are:
#
# 1. There should be a linear relationship between variables.
# 2. Observations should be independent.
# 3. Error variance should be approximately constant.
# 4. Residuals should be approximately normally distributed.
# 5. Independent variables should not have strong
#    multicollinearity.


# Q8. How can overfitting and underfitting affect the performance
# of a regression model?
#
# Answer:
# Overfitting occurs when a model learns the training data too
# closely and performs poorly on unseen data.
#
# Underfitting occurs when a model is too simple to capture the
# important patterns in the data.
#
# A good model should generalize well to unseen data.


# Q9. Mention any three real-world applications of Linear
# Regression in business or industry.
#
# Answer:
#
# 1. House price prediction
# 2. Sales forecasting
# 3. Demand or revenue prediction


# Q10. How can feature selection improve the accuracy and
# interpretability of a predictive model?
#
# Answer:
# Feature selection removes irrelevant or redundant variables.
# It can reduce noise, improve computational efficiency and make
# the model easier to understand.
#
# Selecting important features can also improve model performance
# when irrelevant variables are adding noise.


