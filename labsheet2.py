# Q1. What is Exploratory Data Analysis (EDA), and why is it
# performed before machine learning?
#
# Answer:
# EDA is the process of examining and visualizing a dataset
# to understand its structure, patterns, relationships and
# anomalies. It is performed before machine learning to identify
# data quality problems, understand important features and
# select suitable variables for model building.


# Q2. Differentiate between univariate, bivariate, and
# multivariate analysis with suitable examples.
#
# Answer:
#
# Univariate Analysis:
# Analysis of one variable.
# Example: Distribution of Netflix release years.
#
# Bivariate Analysis:
# Analysis of two variables.
# Example: Release year vs content type.
#
# Multivariate Analysis:
# Analysis of more than two variables.
# Example: Release year, duration and content type together.


# Q3. What insights can be obtained from a correlation heatmap?
#
# Answer:
# A correlation heatmap shows the strength and direction of
# relationships between numerical variables. Values close to
# +1 indicate strong positive correlation, values close to -1
# indicate strong negative correlation, and values near 0
# indicate weak or no linear relationship.


# Q4. Explain the purpose of histograms, box plots, and
# scatter plots in EDA.
#
# Answer:
#
# Histogram:
# Shows the distribution and frequency of numerical data.
#
# Box Plot:
# Shows median, spread and possible outliers.
#
# Scatter Plot:
# Shows the relationship between two numerical variables.


# Q5. How can EDA help identify data quality issues
# before analysis?
#
# Answer:
# EDA can identify missing values, duplicate records, outliers,
# incorrect data types, inconsistent categories and unusual
# distributions. This helps clean the dataset before further
# analysis or machine learning.


# Q6. Why is correlation important in predictive analytics?
# Can correlation imply causation?
#
# Answer:
# Correlation helps identify relationships between variables
# and can help in feature selection. However, correlation does
# not imply causation. Two variables may be correlated without
# one causing the other.


# Q7. Which visualization would you use to analyze categorical
# and numerical variables? Justify your choice.
#
# Answer:
#
# Categorical Variables:
# Bar charts and count plots are suitable because they show
# the frequency of different categories.
#
# Numerical Variables:
# Histograms, box plots and scatter plots are useful because
# they show distribution, outliers and relationships.


# Q8. What business insights can be derived from the Netflix
# dataset through EDA?
#
# Answer:
# EDA can identify:
# 1. The number of Movies and TV Shows.
# 2. Countries producing the most content.
# 3. Most common content ratings.
# 4. Popular genres.
# 5. Trends in content release over the years.
# These insights can support content planning and business
# decision-making.


# Q9. How does EDA contribute to feature selection
# and model building?
#
# Answer:
# EDA helps identify important variables, relationships,
# redundant features, outliers and unusual patterns.
# This helps analysts select useful features and prepare
# better inputs for machine learning models.


# Q10. What challenges might arise while performing EDA
# on large-scale real-world datasets?
#
# Answer:
# Major challenges include:
# 1. Large data size.
# 2. High processing and memory requirements.
# 3. Missing and inconsistent data.
# 4. Large number of features.
# 5. Slow visualization and computation.
# 6. Difficulty in identifying meaningful patterns.


