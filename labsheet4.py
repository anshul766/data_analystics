# different regions? Justify your answer.
#
# Answer:
# A bar chart is suitable because regions are categorical variables.
# It makes comparison between sales of different regions easy.


# Q4. What information can be obtained from a histogram and a
# box plot?
#
# Answer:
# A histogram shows the distribution, frequency and shape of
# numerical data.
# A box plot shows median, quartiles, spread and possible outliers.


# Q5. Explain the purpose of a scatter plot. How does it help in
# identifying relationships between variables?
#
# Answer:
# A scatter plot shows the relationship between two numerical
# variables. It helps identify positive correlation, negative
# correlation, patterns and outliers.


# Q6. What is a correlation heatmap? How can it assist in feature
# selection for machine learning?
#
# Answer:
# A correlation heatmap represents correlation values using colors.
# It helps identify strongly correlated features and can help detect
# redundant features during feature selection.


