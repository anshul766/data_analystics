# Q1. What is the difference between clustering and classification?
# Answer:
# Clustering is an unsupervised learning technique that groups
# similar data points without predefined labels.
# Classification is supervised learning where data is assigned
# to predefined classes using labelled training data.

# Q2. Explain the principle of K-Means clustering.
# Answer:
# K-Means divides data into K clusters.
# It assigns each data point to the nearest centroid and
# repeatedly updates the centroids until the clusters stabilize.

# Q3. Why is scaling important before applying K-Means?
# Answer:
# K-Means uses distance calculations.
# Scaling prevents features with larger numerical values from
# dominating the clustering process.

# Q4. What is the Elbow Method?
# Answer:
# The Elbow Method helps determine the suitable number of clusters.
# It plots K against inertia and the point where the decrease
# starts slowing down is considered the elbow point.

# Q5. What is Silhouette Score?
# Answer:
# Silhouette Score measures how well data points fit within
# their own cluster compared with other clusters.
# Higher values generally indicate better-separated clusters.

# Q6. Is K-Means supervised or unsupervised?
# Answer:
# K-Means is an unsupervised machine learning algorithm because
# it works without predefined class labels.

# Q7. Give four applications of clustering.
# Answer:
# 1. Customer segmentation
# 2. Image segmentation
# 3. Document grouping
# 4. Market analysis

# Q8. What are the limitations of K-Means?
# Answer:
# 1. K must be selected beforehand.
# 2. Sensitive to outliers.
# 3. Sensitive to initial centroids.
# 4. Works best for roughly spherical clusters.

# Q9. How can clustering help in marketing or customer retention?
# Answer:
# Clustering can divide customers into groups based on
# purchasing behaviour, income and spending patterns.
# Businesses can then create suitable offers and strategies
# for different customer groups.

# Q10. Compare K-Means with hierarchical clustering.
# Answer:
# K-Means directly divides data into a predefined number of clusters.
# Hierarchical clustering creates a tree-like structure of clusters.
# K-Means is generally faster for large datasets, while hierarchical
# clustering provides a dendrogram showing relationships between groups.