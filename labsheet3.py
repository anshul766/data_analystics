# ------------------------------------------------------------
# 1. IMPORT REQUIRED LIBRARIES
# ------------------------------------------------------------

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from scipy import stats
from scipy.stats import ttest_ind, f_oneway, pearsonr

import statsmodels.api as sm

from sklearn.linear_model import LinearRegression
from sklearn.metrics import r2_score

print("Libraries imported successfully!")
print("=" * 70)


# ------------------------------------------------------------
# 2. LOAD DATASET
# ------------------------------------------------------------

df = pd.read_csv("Titanic-Dataset.csv")

print("Dataset loaded successfully!")
print("=" * 70)


# ------------------------------------------------------------
# 3. BASIC DATA EXPLORATION
# ------------------------------------------------------------

print("\nFIRST 5 ROWS:")
display(df.head())

print("\nDATASET SHAPE:")
print(df.shape)

print("\nCOLUMN NAMES:")
print(df.columns.tolist())

print("\nDATASET INFORMATION:")
df.info()


# ------------------------------------------------------------
# 4. HANDLE MISSING VALUES
# ------------------------------------------------------------

df["Age"] = df["Age"].fillna(df["Age"].median())

df["Fare"] = df["Fare"].fillna(df["Fare"].median())

print("\nMissing values after treatment:")
print(df.isnull().sum())


# ============================================================
# DESCRIPTIVE STATISTICS
# ============================================================

# ------------------------------------------------------------
# 5. MEAN
# ------------------------------------------------------------

print("\nMEAN:")
print(df[["Age", "Fare"]].mean())


# ------------------------------------------------------------
# 6. MEDIAN
# ------------------------------------------------------------

print("\nMEDIAN:")
print(df[["Age", "Fare"]].median())


# ------------------------------------------------------------
# 7. MODE
# ------------------------------------------------------------

print("\nMODE:")
print(df[["Age", "Fare"]].mode().iloc[0])


# ------------------------------------------------------------
# 8. VARIANCE
# ------------------------------------------------------------

print("\nVARIANCE:")
print(df[["Age", "Fare"]].var())


# ------------------------------------------------------------
# 9. STANDARD DEVIATION
# ------------------------------------------------------------

print("\nSTANDARD DEVIATION:")
print(df[["Age", "Fare"]].std())


# ------------------------------------------------------------
# 10. COMPLETE DESCRIPTIVE STATISTICS
# ------------------------------------------------------------

print("\nCOMPLETE DESCRIPTIVE STATISTICS:")
display(df[["Age", "Fare"]].describe())


# ============================================================
# PEARSON CORRELATION
# ============================================================

# ------------------------------------------------------------
# 11. PEARSON CORRELATION BETWEEN AGE AND FARE
# ------------------------------------------------------------

correlation, correlation_pvalue = pearsonr(
    df["Age"],
    df["Fare"]
)

print("\nPEARSON CORRELATION")
print("Correlation coefficient:", correlation)
print("P-value:", correlation_pvalue)


# ------------------------------------------------------------
# 12. CORRELATION MATRIX
# ------------------------------------------------------------

correlation_matrix = df[
    ["Age", "Fare", "SibSp", "Parch", "Pclass", "Survived"]
].corr()

print("\nCORRELATION MATRIX:")
display(correlation_matrix)


# ------------------------------------------------------------
# 13. CORRELATION HEATMAP
# ------------------------------------------------------------

plt.figure(figsize=(9, 6))

sns.heatmap(
    correlation_matrix,
    annot=True,
    cmap="coolwarm",
    fmt=".2f"
)

plt.title("Correlation Matrix Heatmap")

plt.show()


# ============================================================
# HYPOTHESIS TESTING - INDEPENDENT SAMPLE T-TEST
# ============================================================

# Business Question:
# Is there a significant difference in Fare between
# passengers who survived and passengers who did not survive?


# ------------------------------------------------------------
# 14. CREATE TWO GROUPS
# ------------------------------------------------------------

survived_fare = df[df["Survived"] == 1]["Fare"]

not_survived_fare = df[df["Survived"] == 0]["Fare"]


print("\nAVERAGE FARE OF SURVIVORS:")
print(survived_fare.mean())

print("\nAVERAGE FARE OF NON-SURVIVORS:")
print(not_survived_fare.mean())


# ------------------------------------------------------------
# 15. FORMULATE HYPOTHESES
# ------------------------------------------------------------

# H0 (Null Hypothesis):
# There is NO significant difference in average fare
# between survivors and non-survivors.
#
# H1 (Alternative Hypothesis):
# There IS a significant difference in average fare
# between survivors and non-survivors.


# ------------------------------------------------------------
# 16. INDEPENDENT SAMPLE T-TEST
# ------------------------------------------------------------

t_statistic, t_pvalue = ttest_ind(
    survived_fare,
    not_survived_fare,
    equal_var=False
)

print("\nINDEPENDENT SAMPLE T-TEST")
print("T-statistic:", t_statistic)
print("P-value:", t_pvalue)


# ------------------------------------------------------------
# 17. INTERPRET T-TEST
# ------------------------------------------------------------

alpha = 0.05

if t_pvalue < alpha:
    print("\nDecision: Reject H0")
    print("There is a statistically significant difference.")
else:
    print("\nDecision: Fail to reject H0")
    print("There is no statistically significant difference.")


# ============================================================
# ONE-WAY ANOVA
# ============================================================

# Business Question:
# Is there a significant difference in average Fare
# among different passenger classes?


# ------------------------------------------------------------
# 18. CREATE GROUPS
# ------------------------------------------------------------

class1 = df[df["Pclass"] == 1]["Fare"]

class2 = df[df["Pclass"] == 2]["Fare"]

class3 = df[df["Pclass"] == 3]["Fare"]


print("\nAVERAGE FARE BY PASSENGER CLASS:")

print("Class 1:", class1.mean())

print("Class 2:", class2.mean())

print("Class 3:", class3.mean())


# ------------------------------------------------------------
# 19. FORMULATE ANOVA HYPOTHESES
# ------------------------------------------------------------

# H0:
# There is no significant difference in average fare
# among the three passenger classes.
#
# H1:
# At least one passenger class has a significantly
# different average fare.


# ------------------------------------------------------------
# 20. ONE-WAY ANOVA
# ------------------------------------------------------------

anova_statistic, anova_pvalue = f_oneway(
    class1,
    class2,
    class3
)

print("\nONE-WAY ANOVA")
print("F-statistic:", anova_statistic)
print("P-value:", anova_pvalue)


# ------------------------------------------------------------
# 21. INTERPRET ANOVA
# ------------------------------------------------------------

if anova_pvalue < alpha:
    print("\nDecision: Reject H0")
    print("There is a statistically significant difference")
    print("in average fare among passenger classes.")
else:
    print("\nDecision: Fail to reject H0")
    print("There is no statistically significant difference.")


# ------------------------------------------------------------
# 22. ANOVA VISUALIZATION
# ------------------------------------------------------------

plt.figure(figsize=(8, 5))

sns.boxplot(
    data=df,
    x="Pclass",
    y="Fare"
)

plt.title("Fare Distribution by Passenger Class")
plt.xlabel("Passenger Class")
plt.ylabel("Fare")

plt.show()


# ============================================================
# LINEAR REGRESSION
# ============================================================

# Goal:
# Analyze relationship between Age and Fare.


# ------------------------------------------------------------
# 23. PREPARE DATA
# ------------------------------------------------------------

X = df[["Age"]]

y = df["Fare"]


# ------------------------------------------------------------
# 24. CREATE REGRESSION MODEL
# ------------------------------------------------------------

model = LinearRegression()

model.fit(X, y)


# ------------------------------------------------------------
# 25. PREDICT FARE
# ------------------------------------------------------------

y_pred = model.predict(X)


# ------------------------------------------------------------
# 26. REGRESSION COEFFICIENTS
# ------------------------------------------------------------

print("\nLINEAR REGRESSION RESULTS")

print("Intercept:", model.intercept_)

print("Coefficient:", model.coef_[0])


# ------------------------------------------------------------
# 27. R-SQUARED
# ------------------------------------------------------------

r2 = r2_score(y, y_pred)

print("R² Score:", r2)


# ------------------------------------------------------------
# 28. REGRESSION VISUALIZATION
# ------------------------------------------------------------

plt.figure(figsize=(9, 6))

sns.scatterplot(
    x=df["Age"],
    y=df["Fare"]
)

plt.plot(
    df["Age"],
    y_pred
)

plt.title("Linear Regression: Age vs Fare")

plt.xlabel("Age")

plt.ylabel("Fare")

plt.show()


# ============================================================
# STATSMODELS REGRESSION SUMMARY
# ============================================================

# ------------------------------------------------------------
# 29. STATSMODELS OLS REGRESSION
# ------------------------------------------------------------

X_stats = sm.add_constant(X)

ols_model = sm.OLS(y, X_stats).fit()

print("\nSTATSMODELS REGRESSION SUMMARY:")
print(ols_model.summary())


# ============================================================
# FINAL SUMMARY
# ============================================================

print("\n" + "=" * 70)
print("STATISTICAL ANALYSIS SUMMARY")
print("=" * 70)

print("\nPearson Correlation:", correlation)

print("T-Test P-value:", t_pvalue)

print("ANOVA P-value:", anova_pvalue)

print("Linear Regression R²:", r2)

print("\nStatistical analysis completed successfully!")


