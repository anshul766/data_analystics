# Q1. What is the difference between descriptive statistics
# and inferential statistics?
#
# Answer:
# Descriptive statistics summarizes and describes the data
# using mean, median, mode, variance and standard deviation.
#
# Inferential statistics uses sample data to make conclusions
# or predictions about a larger population using techniques
# such as hypothesis testing and confidence intervals.


# Q2. Explain the concepts of the Null Hypothesis (H0)
# and Alternative Hypothesis (H1).
#
# Answer:
# Null Hypothesis (H0) states that there is no significant
# difference or relationship between variables.
#
# Alternative Hypothesis (H1) states that a significant
# difference or relationship exists.
#
# Example:
# H0: There is no difference in average fare between
# survivors and non-survivors.
#
# H1: There is a difference in average fare between
# survivors and non-survivors.


# Q3. What is a p-value? How is it used to make
# statistical decisions?
#
# Answer:
# A p-value indicates the probability of observing the result
# if the null hypothesis is true.
#
# If p-value < 0.05:
# Reject H0.
#
# If p-value >= 0.05:
# Fail to reject H0.


# Q4. Differentiate between a t-test and ANOVA.
# In which situations is each test applied?
#
# Answer:
# A t-test is generally used to compare the means of two groups.
#
# ANOVA is used to compare the means of three or more groups.
#
# Example:
# T-test -> Survivors vs Non-survivors.
#
# ANOVA -> Fare among Class 1, Class 2 and Class 3.


# Q5. What does the Pearson correlation coefficient indicate?
# What are its possible values?
#
# Answer:
# Pearson correlation measures the strength and direction of
# a linear relationship between two numerical variables.
#
# Its value ranges from -1 to +1.
#
# +1 = Perfect positive correlation.
# -1 = Perfect negative correlation.
#  0 = No linear correlation.


# Q6. Explain the significance of R² (Coefficient of
# Determination) in Linear Regression.
#
# Answer:
# R² measures how much variation in the dependent variable
# is explained by the independent variable.
#
# R² ranges from 0 to 1.
#
# Higher R² generally means the model explains more variation
# in the dependent variable.


# Q7. Why is statistical analysis important before applying
# machine learning algorithms?
