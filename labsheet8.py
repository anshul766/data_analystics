# Q1. What is classification, and how does it differ from regression?
# Answer:
# Classification predicts discrete or categorical classes.
# Regression predicts continuous numerical values.
# Example: Churn prediction is classification, while house price
# prediction is regression.

# Q2. Explain the working principle of the Decision Tree algorithm.
# Answer:
# A Decision Tree repeatedly splits the dataset using features
# and conditions. Each split creates branches and the final
# leaf node gives the predicted class.

# Q3. Differentiate between Gini Index and Entropy as splitting criteria.
# Answer:
# Gini Index measures the probability of incorrect classification.
# Entropy measures the impurity or uncertainty in the dataset.
# Both are used to select suitable splits in a Decision Tree.

# Q4. What is a Confusion Matrix? Explain its components.
# Answer:
# A Confusion Matrix compares actual and predicted classes.
#
# TP = True Positive
# TN = True Negative
# FP = False Positive
# FN = False Negative

# Q5. Define Accuracy, Precision, Recall, and F1-Score.
# Answer:
# Accuracy = Correct Predictions / Total Predictions
#
# Precision = TP / (TP + FP)
#
# Recall = TP / (TP + FN)
#
# F1-Score = 2 * (Precision * Recall) /
#            (Precision + Recall)
#
# These metrics help evaluate different aspects of classification
# performance.

# Q6. What is overfitting in a Decision Tree? How can it be reduced?
# Answer:
# Overfitting occurs when a Decision Tree learns the training data
# too closely and performs poorly on unseen data.
# It can be reduced using max_depth, min_samples_split,
# min_samples_leaf, pruning and cross-validation.

# Q7. Why is customer churn prediction important for businesses?
# Answer:
# Churn prediction helps businesses identify customers who may
# leave the service. This allows organizations to take early
# retention actions and reduce customer and revenue loss.

# Q8. What are the advantages and limitations of Decision Tree?
# Answer:
# Advantages:
# 1. Easy to understand and interpret.
# 2. Requires little data preprocessing.
# 3. Works with numerical and categorical data.
# 4. Useful for explaining decision rules.
#
# Limitations:
# 1. Can overfit easily.
# 2. Small data changes can change the tree.
# 3. Large trees can become complex.

# Q9. Mention three real-world applications of Decision Tree
# Classification other than customer churn prediction.
# Answer:
# 1. Medical disease diagnosis
# 2. Loan approval / credit risk classification
# 3. Spam email detection

# Q10. How can churn prediction insights improve customer retention
# and business profitability?
# Answer:
# Churn prediction identifies important factors related to customer
# leaving. Businesses can target high-risk customers with suitable
# offers, better services, discounts and loyalty programs.
# This can help improve retention and reduce revenue loss.